/**
 * 낚시 제목 패턴 — **단일 출처**.
 *
 * 예전에는 content-generator(발행 게이트), scripts/blog-merge/clickbait-patterns(재작성),
 * scripts/blog-merge/audit-titles(감사)가 각자 복사본을 들고 있었다. 셋이 어긋나면서
 * 재작성이 "통과"라고 판정한 제목이 감사에서는 위반이고, 게이트는 또 다른 기준이었다.
 * 실제로 1차 재작성 뒤에도 "아직도 … 놓치실 건가요?"가 남아 병합 승자로 뽑혔다.
 *
 * 게이트는 2026-08-21에 추가됐고 그 이전 발행분 1,306편은 통과한 적이 없다.
 * 실측: 최초 감사 566편(43.3%) 위반 → 564편 재작성 완료.
 */

/** 최초 게이트(2026-08-21). 지금은 EXTRA까지 합친 ALL_PATTERNS가 게이트다 — 기록용으로 남긴다. */
export const GATE_PATTERNS: readonly RegExp[] = [
  /모르면/,
  /고점에\s*물/,
  /확률\s*\d+\s*%/,
  /아직도.*(하시나요|보시나요|계신가요)/,
  /나만\s*손해/,
  /안\s*보면/,
  /지금\s*아니면/,
  /충격/,
  /(?:^|\s)썰(?:\s|$|\.)/,
  /후회/,
];

/**
 * 게이트에는 없지만 실측 제목에서 반복 확인된 낚시 패턴.
 *
 * 활용형까지 잡는다. 1차 재작성(564편) 뒤에도 "아직도 예전 종목만 보다가 수익
 * 놓치실 건가요?"가 병합 승자로 뽑혔다 — `아직도.*하시나요`와 `놓치면`은 이 어미를
 * 비껴간다. 어간(`놓치`, `아직도`)과 어미를 나눠 매칭한다.
 */
export const EXTRA_PATTERNS: readonly RegExp[] = [
  /남들\s*다/,
  /(날렸|잃었)습니다/,
  /물(립니다|리지|힙니다)/,
  /놓치(면|실|시면|는|지)/,
  /아직도.*(가요|나요|건가요|겁니까|습니까|\?)/,
  /(소외됩니다|구경만)/,
  /수익\s*0원/,
  /(의 비밀|진짜 이유)/,
  /큰일\s*(납니다|나요)/,
  /(했다간|하다간|들어갔다간)/,
  /(진짜|찐)['"’]?는?\s*따로/,
  /이것만\s*(보|알)/,
  /(폭락|급락|폭등)\s*(전|직전)/,
  /(주의|경고)하세요/,
  /(반드시|꼭)\s*확인/,
];

/** 발행 게이트이자 감사 기준. 둘을 다르게 두면 통과한 글이 나중에 위반으로 잡힌다. */
export const ALL_PATTERNS: readonly RegExp[] = [...GATE_PATTERNS, ...EXTRA_PATTERNS];

export function isClickbait(title: string): boolean {
  return ALL_PATTERNS.some((re) => re.test(title));
}

/**
 * 매수·수익 단정 — 자본시장법상 투자권유·유사투자자문 경계 표현.
 *
 * 두 트랙이 공유한다. 트랙 A는 YMYL 게이트에서 생성물 전체를, 트랙 B는 인용할
 * 기사 제목을 이 패턴으로 거른다. 인용이라도 본문에 실리면 같은 글에 실린 문장이다.
 *
 * 이 모듈에 두는 이유: 의존성이 없다. `_services/ymyl-gate`는 Supabase 클라이언트를
 * 끌고 오므로, 정규식 하나 때문에 트랙 B(네이버)가 트랙 A의 DB 체인에 묶이면 안 된다.
 *
 * 명령형 권유(`매수하세요`, `매수를 권합니다`, `지금 사세요`, `담으세요`)가 빠져 있었다 —
 * 가장 직접적인 투자권유 형태인데 게이트를 통과했다.
 */
export const INVESTMENT_SOLICITATION_RE =
  /(지금\s*(매수|사야|사세요|들어가|담으)|매수\s*(추천|타이밍|적기|하세요|하시길)|매수를?\s*(권|추천)|사세요|담으세요|비중을?\s*(늘리세요|실으)|목표가\s*[\d,]+원|수익률?\s*\d+\s*%\s*(보장|확실)|무조건\s*(오른다|상승)|급등\s*(예정|확실)|반드시\s*(오른|상승))/;
