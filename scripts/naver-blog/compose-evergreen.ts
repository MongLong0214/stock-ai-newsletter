export const EVERGREEN_TOPIC_COUNT = TOPICS.length;

/** 몇 번째 evergreen 차례인지로 주제를 고른다 — 발행 회차가 아니라 evergreen 회차다. */
export function composeEvergreen(
  evergreenIndex: number,
  ctx: EvergreenContext,
  siteUrl: string,
): { body: string; slug: string; tags: string[]; title: string } {
  const topic = TOPICS[((evergreenIndex % TOPICS.length) + TOPICS.length) % TOPICS.length];
  const [y, m] = ctx.asOf.split('-');

  const sectionBlocks = topic.sections.flatMap(([heading, ...paras], index) => {
    const image = index === 0
      ? ['{{image:2-section}}']
      : index === 1
        ? ['{{image:3-section}}']
        : index === 2
          ? ['{{image:4-section}}']
          : [];
    if (index < 3) return [`${QUOTE}${heading}`, ...paras, ...image];
    return [`**${heading}**`, ...paras];
  });

  const facts =
    `기준일은 ${b(ctx.asOf)}입니다. 단계별 상위 표본 ${b(`${ctx.sampledThemes}개`)} 가운데 ` +
    `${b(`${ctx.risers7d}개`)}가 최근 7일 동안 점수가 올랐고, 최상위는 ${b(ctx.topName)}입니다. ` +
    `점수는 ${b(`${ctx.topScore}점`)}, 단계는 ${b(ctx.topStageKo)}이며 수집 범위는 ${b('최근 30일')}입니다.`;

  const blocks = [
    topic.lead(ctx),
    facts,
    '{{image:1-hero}}',
    ...sectionBlocks,
    `${QUOTE}정리`,
    topic.close(ctx),
    '이 점수는 네이버 데이터랩 검색 트렌드와 뉴스 건수, KRX 시세를 매일 자동 집계해 계산한 ' +
      '참고용 데이터입니다. 특정 종목의 매수·매도를 권하는 것이 아니며, 투자 판단과 그 결과는 ' +
      '투자자 본인의 책임입니다.',
    `사실 확인에 활용한 데이터: 네이버 데이터랩, 네이버 뉴스, KRX 시세 (기준일 ${ctx.asOf})`,
    `${siteUrl}/themes/methodology`,
  ];

  return {
    slug: topic.slug,
    title: `${topic.title} (${y}.${m})`,
    body: blocks.join('\n\n'),
    tags: [...topic.tags],
  };
}
